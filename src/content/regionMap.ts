// Регион, в котором игра начинается (вокруг базы «Кедр-1»).
export const START_REGION_ID = 'region_basin';

/**
 * Какой файл с контентом загружать для каждого региона.
 * Запись `() => import('./regions/…')` означает «загрузить файл, только когда попросят»:
 * сборщик (Vite) кладёт каждый регион в отдельный маленький файл, и браузер скачивает
 * его лишь при подходе курьера к региону, а не при запуске игры.
 */
export const REGION_FILES: Record<string, () => Promise<RegionContentModule>> = {
  region_basin: () => import('./regions/yenisei-basin'),
  region_river: () => import('./regions/ice-river'),
  region_ridge: () => import('./regions/north-ridge'),
  region_marsh: () => import('./regions/dead-marsh'),
  region_rift: () => import('./regions/permafrost-rift'),
  region_valley: () => import('./regions/anomaly-valley'),
  region_taiga: () => import('./regions/deep-taiga')
};

// Быстрый поиск карточки региона по id.
export function getRegionById(id: string): RegionDefinition | undefined {
  return REGIONS.find(r => r.id === id);
}

/**
 * В каком регионе находится точка (x, y), координаты — в клетках карты.
 * Правила проверяются сверху вниз, первое подошедшее и есть ответ. Порядок важен:
 * река проверяется первой и «прорезает» все остальные регионы.
 * Карта 120×120 клеток: x растёт слева направо, y — сверху вниз (север сверху).
 */
export function getRegionAt(x: number, y: number): RegionDefinition {
  // Река — извилистая линия. Центр русла на строке y считается по формуле из двух синусоид,
  // той же, по которой mapGenerator рисует лёд. 3.2 клетки — полуширина русла вместе
  // с берегом (сам лёд чуть уже, 2.5 клетки).
  const riverX = 45 + Math.sin(y * 0.08) * 14 + Math.cos(y * 0.03) * 10;
  if (Math.abs(x - riverX) < 3.2) {
    return getRegionById('region_river')!;
  }

  // Северный Хребет: северо-восточная четверть карты.
  if (x >= 52 && y <= 35) {
    return getRegionById('region_ridge')!;
  }

  // Глухая Тайга: восток, севернее середины карты.
  if (x >= 82 && y <= 50) {
    return getRegionById('region_taiga')!;
  }

  // Мёртвая Топь: низина к югу от старта, где бродят Хладные Тени.
  if (x >= 15 && x <= 48 && y >= 45 && y <= 68) {
    return getRegionById('region_marsh')!;
  }

  // Мерзлотный разлом: юго-запад, каньон вокруг прииска.
  if (x >= 15 && x <= 56 && y >= 69) {
    return getRegionById('region_rift')!;
  }

  // Аномальная Долина: юго-восток вокруг бункера «Север-4».
  if (x >= 68 && y >= 55) {
    return getRegionById('region_valley')!;
  }

  // Всё остальное — стартовый Енисейский бассейн.
  return getRegionById('region_basin')!;
}
