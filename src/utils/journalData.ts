// Helper to get all entries unlocked by a list of explored region IDs
export function getUnlockedEntries(discoveredRegionIds: string[]): JournalEntry[] {
  const regionSet = new Set(discoveredRegionIds);
  return JOURNAL_ENTRIES.filter(entry => regionSet.has(entry.regionId));
}

// Helper to get entries for a specific region
export function getEntriesForRegion(regionId: string): JournalEntry[] {
  return JOURNAL_ENTRIES.filter(entry => entry.regionId === regionId);
}
