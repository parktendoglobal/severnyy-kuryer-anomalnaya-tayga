export function getRegionAt(x: number, y: number): RegionDefinition {
  // River check first: winding S-curve through the world
  const riverX = 45 + Math.sin(y * 0.08) * 14 + Math.cos(y * 0.03) * 10;
  if (Math.abs(x - riverX) < 3.2) {
    return REGIONS.find(r => r.id === 'region_river')!;
  }

  // Northern Mountains / Ridge: high altitude north/north-east
  if (x >= 52 && y <= 35) {
    return REGIONS.find(r => r.id === 'region_ridge')!;
  }

  // Deep Ancient Taiga: far north-east / east upper sector
  if (x >= 82 && y <= 50) {
    return REGIONS.find(r => r.id === 'region_taiga')!;
  }

  // Dead Marsh: mid-west lowlands where phantoms roam
  if (x >= 15 && x <= 48 && y >= 45 && y <= 68) {
    return REGIONS.find(r => r.id === 'region_marsh')!;
  }

  // Permafrost Rift: south-west rocky canyon around Mine
  if (x >= 15 && x <= 56 && y >= 69) {
    return REGIONS.find(r => r.id === 'region_rift')!;
  }

  // Anomaly Valley: south-east ground zero around Bunker
  if (x >= 68 && y >= 55) {
    return REGIONS.find(r => r.id === 'region_valley')!;
  }

  // Default: Yenisey Basin (starting area and surrounding plains)
  return REGIONS.find(r => r.id === 'region_basin')!;
}

